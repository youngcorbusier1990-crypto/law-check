/* art 문자열에서 정확한 원문 링크 생성 */
function buildLawLink(art){
  // 1) 매핑 테이블 우선
  for(const [kw,name] of LAW_NAME_MAP){
    if(art.indexOf(kw)>=0) return LAW_URL+encodeURIComponent(name);
  }
  // 2) "건축법 제X조" 계열 → 건축법
  if(art.indexOf("건축법")===0) return LAW_URL+encodeURIComponent("건축법");
  // 3) fallback: 첫 토큰(괄호·조번호 제거)
  const base=art.split(" ")[0].replace(/\(.*$/,"").replace(/제\d+조.*$/,"");
  return LAW_URL+encodeURIComponent(base||art);
}

/* 자치법규(조례) 검색 링크 — 지자체명 + 조례명으로 국가법령정보센터 자치법규 검색 */
const ORDIN_URL = "https://www.law.go.kr/ordinSc.do?menuId=3&subMenuId=27&tabMenuId=139&query=";
function buildOrdinanceLink(gov, ordinName){
  const q = (gov?gov+" ":"") + ordinName;
  return ORDIN_URL + encodeURIComponent(q);
}

